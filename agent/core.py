import anyio
from dotenv import load_dotenv
from claude_agent_sdk import (
    query,
    ClaudeAgentOptions,
    AgentDefinition,
    ResultMessage,
    SystemMessage,
)

from . import repo as repo_manager
from . import logger

load_dotenv()


# ── Config Helpers ────────────────────────────────────────────────────────────

def load_config() -> dict:
    config_path = Path("config.yaml")
    if not config_path.exists():
        raise FileNotFoundError(
            "config.yaml not found. Run from the dev-agent/ directory."
        )
    with open(config_path) as f:
        return yaml.safe_load(f)


def resolve_repo(config: dict, repo_name: str) -> dict:
    """
    Merge repo_type defaults with per-repo overrides.
    The repo entry always wins over the type template.
    """
    repo = config["repos"][repo_name]
    type_name = repo.get("type")

    if not type_name:
        return repo

    repo_types = config.get("repo_types", {})
    if type_name not in repo_types:
        raise ValueError(
            f"Repo type '{type_name}' not found in config.yaml repo_types.\n"
            f"Available types: {list(repo_types.keys())}"
        )

    # Type defaults + repo overrides (repo wins on conflict)
    resolved = {**repo_types[type_name], **repo}
    return resolved


def load_prompt(name: str) -> str:
    path = Path(f"prompts/{name}.md")
    if not path.exists():
        raise FileNotFoundError(f"Prompt file missing: {path}")
    return path.read_text(encoding="utf-8")


def read_repo_context(repo_path: str) -> str:
    """
    Read README.md and .claude/CLAUDE.md from the repo.
    Injected into the task prompt so the agent starts with full context.
    """
    sections = []
    root = Path(repo_path)

    readme = root / "README.md"
    if readme.exists():
        sections.append(
            f"## README.md\n\n{readme.read_text(encoding='utf-8')}"
        )

    claude_md = root / ".claude" / "CLAUDE.md"
    if claude_md.exists():
        sections.append(
            f"## .claude/CLAUDE.md\n\n"
            f"IMPORTANT: Follow every rule in this file.\n\n"
            f"{claude_md.read_text(encoding='utf-8')}"
        )

    if not sections:
        return "(No README.md or .claude/CLAUDE.md found in this repo.)"

    return (
        "# REPO CONTEXT — Read This Before Starting\n\n"
        + "\n\n---\n\n".join(sections)
    )


def build_quality_checks(repo: dict) -> str:
    """
    Build the quality check instructions from resolved repo config.
    Fully dynamic — works for any repo type.
    """
    checks = []

    if repo.get("typecheck_command"):
        checks.append(
            f"1. TypeScript check : {repo['typecheck_command']}\n"
            f"   Fix ALL type errors before continuing."
        )
    if repo.get("lint_command"):
        checks.append(
            f"2. Lint             : {repo['lint_command']}\n"
            f"   Fix ALL lint errors before continuing."
        )
    if repo.get("format_check_command"):
        checks.append(
            f"3. Format check     : {repo['format_check_command']}\n"
            f"   If it fails, run: {repo.get('format_fix_command', 'fix manually')}"
        )
    if repo.get("test_command"):
        snapshot_note = ""
        if repo.get("snapshot_reset_command"):
            snapshot_note = (
                f"\n   If snapshot failures: run `{repo['snapshot_reset_command']}` first, "
                f"then re-run tests."
            )
        checks.append(
            f"4. Tests            : {repo['test_command']}{snapshot_note}"
        )

    return "\n\n".join(checks) if checks else "Run: npm test"


def build_repo_settings(repo_name: str, repo: dict, repo_path: str) -> str:
    """Build the REPO SETTINGS block injected into the task prompt."""
    lines = [
        f"Repo name     : {repo_name}",
        f"Type          : {repo.get('type', 'custom')}",
        f"Language      : {repo.get('language', 'TypeScript')}",
        f"Framework     : {repo.get('framework', '')}",
        f"Local path    : {repo_path}",
        f"Main branch   : {repo.get('main_branch', 'main')}",
        f"GitHub URL    : {repo.get('github_url', 'not set')}",
        f"Test files    : {repo.get('test_file_pattern', '')}",
        f"Path alias    : {repo.get('path_alias', '')}",
    ]
    if repo.get("zod_import"):
        lines.append(f"Zod import    : {repo['zod_import']}")
    if repo.get("coverage_target"):
        lines.append(f"Coverage      : {repo['coverage_target']} target")
    if repo.get("protected_files"):
        lines.append(f"DO NOT MODIFY : {', '.join(repo['protected_files'])}")
    if repo.get("autogenerated_dirs"):
        lines.append(f"DO NOT EDIT   : {', '.join(repo['autogenerated_dirs'])} (auto-generated)")
    if repo.get("notes"):
        lines.append(f"Notes         : {repo['notes']}")

    return "\n".join(f"- {line}" for line in lines if line.split(":")[1].strip())


# ── Main Entry Point ──────────────────────────────────────────────────────────

async def run(repo_name: str, story: str):
    """Run the full agent pipeline on a repo with a given user story."""

    config = load_config()

    if repo_name not in config["repos"]:
        available = list(config["repos"].keys())
        print(f"\nUnknown repo: '{repo_name}'")
        print(f"Available   : {available}")
        return

    # Resolve type defaults + repo overrides
    repo = resolve_repo(config, repo_name)

    print(f"\n{'=' * 52}")
    print(f"  Dev Agent  |  {repo_name}  [{repo.get('type', 'custom')}]")
    print(f"{'=' * 52}")

    print("\n[1/3] Locating repo...")
    repo_path = repo_manager.prepare(repo)
    print(f"  {repo_path}")

    print("[2/3] Reading repo context (README + CLAUDE.md)...")
    repo_context = read_repo_context(repo_path)

    print("[3/3] Launching agent...\n")

    # Build task prompt with all dynamic settings
    main_branch     = repo.get("main_branch", "main")
    personal_ctx    = config.get("personal_context", "")
    quality_checks  = build_quality_checks(repo)
    repo_settings   = build_repo_settings(repo_name, repo, repo_path)

    task_prompt = f"""\
{personal_ctx}

---

{repo_context}

---

USER STORY:
{story}

---

REPO SETTINGS:
{repo_settings}

---

QUALITY CHECKS — Run all of these in order before raising the PR:
{quality_checks}

---

INSTRUCTIONS:
- Work fully autonomously — do not ask for permission at any point
- Read existing code before writing anything — never guess
- Never push directly to `{main_branch}`
- feature/<name> for new features, fix/<name> for bugs
- All quality checks above must pass before raising the PR
- Raise the PR once everything is green
"""

    # Load prompts
    orchestrator_prompt = load_prompt("orchestrator")
    code_writer_prompt  = load_prompt("code_writer")
    reviewer_prompt     = load_prompt("reviewer")
    tester_prompt       = load_prompt("tester")

    result_text = ""

    async for message in query(
        prompt=task_prompt,
        options=ClaudeAgentOptions(
            cwd=repo_path,
            model=config.get("model", "claude-opus-4-6"),
            allowed_tools=["Read", "Write", "Edit", "Bash", "Glob", "Grep", "Agent"],
            permission_mode="bypassPermissions",
            system_prompt=orchestrator_prompt,
            max_turns=config.get("max_turns", 80),
            agents={
                "code-writer": AgentDefinition(
                    description=(
                        "Senior TypeScript engineer. Reads the codebase, implements "
                        "features following all CLAUDE.md rules, writes production-quality "
                        "code with tests."
                    ),
                    prompt=code_writer_prompt,
                    tools=["Read", "Write", "Edit", "Glob", "Grep"],
                ),
                "code-reviewer": AgentDefinition(
                    description=(
                        "Staff engineer. Reviews code for correctness, security, style, "
                        "and test coverage. Returns APPROVED or CHANGES REQUESTED with "
                        "specific file and line references."
                    ),
                    prompt=reviewer_prompt,
                    tools=["Read", "Glob", "Grep", "Bash"],
                ),
                "test-runner": AgentDefinition(
                    description=(
                        "QA engineer. Runs all quality checks (typecheck, lint, prettier, "
                        "tests) using the commands provided in the task. Reports pass/fail "
                        "with exact error details."
                    ),
                    prompt=tester_prompt,
                    tools=["Read", "Bash", "Glob"],
                ),
            },
        ),
    ):
        if isinstance(message, ResultMessage):
            result_text = message.result
            print("\n[DONE] Agent finished!\n")
            print(result_text)

        elif isinstance(message, SystemMessage) and message.subtype == "init":
            session_id = message.data.get("session_id", "unknown")
            print(f"  Session: {session_id}\n")

    logger.save(repo_name, story, result_text)
